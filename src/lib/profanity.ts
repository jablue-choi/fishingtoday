const RE = new RegExp(WORDS.join('|'))
// 띄어쓰기를 지우면 욕처럼 붙는 일상어 ('날씨 발표' → '날씨발표')
const SAFE = /시발점|시발역|날씨|솜씨|아저씨|아가씨|글씨|말씨|마음씨|맵시/g

export function hasProfanity(t: string) {
  const n = t.replace(/[^가-힣a-zA-Zㄱ-ㅎㅏ-ㅣ]/g, '').toLowerCase().replace(SAFE, '')
  return RE.test(n)
}

