--  - 해역별 시즌·제철 월, 추천 방법·미끼, 한 줄 팁
--  - 값은 일반적인 안내용 (지역·수온에 따라 달라짐). 금어기 제외는 앱에서 closed_season_rules로 처리
create table if not exists public.species_seasons (
  id           serial primary key,
  species_id   int not null references public.species(id),
  area         text not null check (area in ('서해','남해','동해','제주','민물')),
  months       smallint[] not null,               -- 낚이는 달
  peak_months  smallint[] not null default '{}',  -- 제철
  methods      text[] not null default '{}',      -- 화면 표시용 라벨
  baits        text[] not null default '{}',
  tip          text,
  unique (species_id, area)
);

